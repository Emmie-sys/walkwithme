import { request, setAuthToken } from './http';
import type { Invitation, Message, Notice, Settings, User, Walk } from '../types';

export const api = {
  login: async (email: string, password: string) => { const result = await request<{token:string; user:User}>('/auth/login', { method:'POST', body:JSON.stringify({email,password}) }); setAuthToken(result.token); return result.user; },
  register: async (data: {name:string; email:string; studentId:string; password:string}) => { const result = await request<{token:string; user:User}>('/auth/register', { method:'POST', body:JSON.stringify(data) }); setAuthToken(result.token); return result.user; },
  logout: () => setAuthToken(null),
  home: () => request<{friends:User[]; invitations:Invitation[]; walks:Walk[]}>('/home'),
  friends: () => request<{friends:User[]; requests:{id:string;user:User;createdAt:string}[]}>('/friends'),
  searchStudents: (query:string) => request<User[]>(`/students?q=${encodeURIComponent(query)}`),
  requestFriend: (userId:string) => request('/friends/requests', {method:'POST', body:JSON.stringify({userId})}),
  acceptFriend: (id:string) => request(`/friends/requests/${id}/accept`, {method:'POST'}),
  declineFriend: (id:string) => request(`/friends/requests/${id}/decline`, {method:'POST'}),
  removeFriend: (id:string) => request(`/friends/${id}`, {method:'DELETE'}),
  settings: () => request<Settings>('/settings'),
  saveSettings: (settings:Settings) => request<Settings>('/settings', {method:'PATCH', body:JSON.stringify(settings)}),
  activeWalk: () => request<Walk|null>('/walks/active'),
  walks: () => request<Walk[]>('/walks'),
  createWalk: (data:{originId:string; destinationId:string; inviteUserIds:string[]; sharingEnabled:boolean}) => request<Walk>('/walks', {method:'POST', body:JSON.stringify(data)}),
  endWalk: (id:string) => request(`/walks/${id}/end`, {method:'POST'}),
  leaveWalk: (id:string) => request(`/walks/${id}/leave`, {method:'POST'}),
  setWalkSharing: (id:string,sharingEnabled:boolean) => request<Walk>(`/walks/${id}/sharing`, {method:'PATCH',body:JSON.stringify({sharingEnabled})}),
  inviteToWalk: (id:string, userId:string) => request(`/walks/${id}/invitations`, {method:'POST', body:JSON.stringify({userId})}),
  walkInvitations: (id:string) => request<{id:string;recipientId:string}[]>(`/walks/${id}/invitations`),
  invitations: () => request<Invitation[]>('/invitations'),
  answerInvitation: (id:string, accept:boolean) => request(`/invitations/${id}/${accept?'accept':'decline'}`, {method:'POST'}),
  messages: (id:string) => request<Message[]>(`/walks/${id}/messages`),
  sendMessage: (id:string, body:string) => request<Message>(`/walks/${id}/messages`, {method:'POST', body:JSON.stringify({body})}),
  notices: () => request<Notice[]>('/notifications'),
  markRead: (id?:string) => request('/notifications/read', {method:'POST', body:JSON.stringify({id})}),
  report: (body:string) => request('/reports', {method:'POST', body:JSON.stringify({body})}),
  sos: () => request('/safety/sos', {method:'POST'}),
  checkIn: () => request('/safety/check-in', {method:'POST'}),
  safetyEvents: () => request<{id:string;kind:string;body:string;createdAt:string}[]>('/safety/events'),
};
